function fillParams(s, p){ return p ? s.replace(/\{(\w+)\}/g,(m,k)=>(p[k]===undefined?m:p[k])) : s; }
/* ข้อความในภาษาที่ระบุ (ไม่มีคำแปล → ใช้ไทย) */
function tr(key, p, lang){
  const e=STR[key]; if(!e) return key;
  return fillParams(e[lang||LANG]||e.th, p);
}
/* ข้อความล้วน ภาษาปัจจุบัน */
function T(key, p){ return tr(key, p, LANG); }
/* HTML สองภาษา: โหมดพม่า = พม่า + ไทยตัวเล็ก / โหมดไทย = ไทยอย่างเดียว */
function TH(key, p){
  const esc2=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
  if(LANG==='my' && STR[key] && STR[key].my) return '<span class="l-my">'+esc2(tr(key,p,'my'))+'</span><span class="l-sub">'+esc2(tr(key,p,'th'))+'</span>';
  return esc2(tr(key,p,'th'));
}
/* ทั้งสองภาษาเสมอ (ใช้หน้าแรกที่ยังไม่รู้ว่าใครอ่าน และในสลิป) */
function TB(key, p){
  const esc2=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
  return esc2(tr(key,p,'th'))+'<span class="l-sub l-my">'+esc2(tr(key,p,'my'))+'</span>';
}
function typeLabel(v, lang){ return TYPE_KEY[v] ? tr(TYPE_KEY[v],null,lang) : String(v||''); }
function statusLabel(v, lang){ return STATUS_KEY[v] ? tr(STATUS_KEY[v],null,lang) : String(v||''); }
function approvalLabel(v, lang){ return APPROVAL_KEY[v] ? tr(APPROVAL_KEY[v],null,lang) : String(v||''); }
/* แปล error จากหลังบ้านตามรหัส (ไม่มีรหัส → ใช้ข้อความไทยที่หลังบ้านส่งมา) */
function errText(res){
  if(res && res.code && STR['E_'+res.code]){
    return T('E_'+res.code, { d: res.min_date ? fmtDMY(res.min_date) : '', name: res.holiday||'', days: (res.days===undefined?'':res.days),
      slots: (/^OT_/.test(res.code) && typeof otCompact==='function') ? otCompact(res.slots||[]) : (res.slots||[]).join(', ') });
  }
  return (res && res.error) || T('e_generic');
}
/* เติมข้อความลงใน element ที่มี data-i18n / data-i18n-bi / data-i18n-ph */
function applyI18n(root){
  root=root||document;
  root.querySelectorAll('[data-i18n]').forEach(el=>{ el.innerHTML=TH(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-bi]').forEach(el=>{ el.innerHTML=TB(el.getAttribute('data-i18n-bi')); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el=>{ el.setAttribute('placeholder', T(el.getAttribute('data-i18n-ph'))); });
  document.documentElement.setAttribute('data-lang', LANG);
  document.documentElement.setAttribute('lang', LANG==='my'?'my':'th');
}
function setLang(l){
  if(l!=='th' && l!=='my') return;
  LANG=l;
  try{ localStorage.setItem('lv_lang', l); }catch(e){}
  applyI18n();
  if(typeof onLangChange==='function') onLangChange();
}
